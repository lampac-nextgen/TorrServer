/**
 * Renders `palettes.json` into the palette stylesheet. Shared by `scripts/gen-palettes.mjs`
 * (writes `src/palettes.generated.css`) and the palette tests (assert the file is current).
 */

const GROUPS = [
  ['background', 'foreground'],
  ['surface', 'surface-secondary', 'surface-tertiary'],
  ['muted', 'border', 'separator'],
  ['accent', 'accent-foreground', 'accent-secondary'],
  ['danger', 'danger-foreground', 'warning', 'warning-foreground', 'success', 'success-foreground'],
  ['app-header', 'app-header-foreground', 'app-rail', 'app-rail-foreground'],
]

export const PALETTE_TOKENS = GROUPS.flat()

function block(selector, tokens, id, mode) {
  const groups = GROUPS.map(keys =>
    keys
      .map(key => {
        if (tokens[key] === undefined) throw new Error(`palette ${id} (${mode}) is missing --${key}`)
        return `  --${key}: ${tokens[key]};`
      })
      .join('\n'),
  )
  return `${selector} {\n${groups.join('\n\n')}\n}\n`
}

/** @param {{ default: string, palettes: Array<{ id: string, note?: string, light: Record<string,string>, dark: Record<string,string> }> }} data */
export function renderPalettesCss(data) {
  const parts = [
    '/* AUTO-GENERATED by scripts/gen-palettes.mjs from src/shared/theme/palettes.json — do not edit by hand. */\n',
  ]
  for (const p of data.palettes) {
    const isDefault = p.id === data.default
    const light = isDefault ? `:root,\n:root[data-palette='${p.id}']` : `:root[data-palette='${p.id}']`
    const dark = isDefault ? `.dark,\n.dark[data-palette='${p.id}']` : `.dark[data-palette='${p.id}']`
    const note = p.note ? `/* ${p.note} */\n` : ''
    parts.push(`${note}${block(light, p.light, p.id, 'light')}\n${block(dark, p.dark, p.id, 'dark')}`)
  }
  parts.push(`/*
 * HeroUI ships its own neutral chrome (zinc grays: overlays, default buttons, fields, segments).
 * Map it onto the palette tokens so dialogs, popovers, chips and inputs follow every palette.
 */
:root {
  --overlay: var(--surface);
  --overlay-foreground: var(--foreground);
  --default: var(--surface-tertiary);
  --default-foreground: var(--foreground);
  --field-background: var(--surface-secondary);
  --field-foreground: var(--foreground);
  --segment: var(--surface);
  --segment-foreground: var(--foreground);
}

.dark {
  --overlay: var(--surface-secondary);
  --field-background: var(--surface);
  --segment: color-mix(in srgb, var(--surface-tertiary) 80%, var(--foreground));
}

/*
 * Increased-contrast preference: push secondary text and hairlines toward the foreground
 * for every palette. Same specificity as the palette blocks and later in the file, so it wins.
 */
@media (prefers-contrast: more) {
  :root[data-palette] {
    --muted: color-mix(in srgb, var(--foreground) 82%, var(--surface));
    --border: color-mix(in srgb, var(--foreground) 55%, var(--surface));
    --separator: color-mix(in srgb, var(--foreground) 40%, var(--surface));
  }
}
`)
  return parts.join('\n')
}

/**
 * The data block of the pre-paint script in index.html: retired-palette aliases and the header
 * colours (light, dark) used for `theme-color`. Spliced between the markers by gen-palettes.mjs.
 */
export function renderPrepaintData(data) {
  const headers = Object.fromEntries(data.palettes.map(p => [p.id, [p.light['app-header'], p.dark['app-header']]]))
  return `var ALIASES = ${JSON.stringify(data.aliases ?? {})}\n          var HEADERS = ${JSON.stringify(headers)}`
}

export const PREPAINT_START = '/*palettes:start*/'
export const PREPAINT_END = '/*palettes:end*/'

/** Replace the marked region of an index.html with the current data. */
export function spliceIndexHtml(html, data) {
  const a = html.indexOf(PREPAINT_START)
  const b = html.indexOf(PREPAINT_END)
  if (a < 0 || b < a) throw new Error('index.html: pre-paint markers not found')
  return `${html.slice(0, a + PREPAINT_START.length)}\n          ${renderPrepaintData(data)}\n          ${html.slice(b)}`
}
